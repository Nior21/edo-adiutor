$ErrorActionPreference = "Stop"
$root = "C:\\Projects\\1C\\Управление_закупками\\ПомощникДляЭДО"
$mod = Get-ChildItem (Join-Path $root "src\ExternalDataProcessors\*\Forms\Форма\Module.bsl") | Select-Object -First 1 -ExpandProperty FullName
$t = [IO.File]::ReadAllText($mod, [Text.UTF8Encoding]::new($false))
if ($t -match "ПаузаМсHTTPНаСервере") {
  Write-Host "Already patched"
  exit 0
}

$pattern = '(?s)\tПопытка\r?\n\t\tСоединение = Новый HTTPСоединение\(URI\.Хост, Порт, , , , 60,.*?\tКонецПопытки;'
$replacement = @'
	HTTPОшибка = "";
	Для НомерПопытки = 1 По 3 Цикл
		Попытка
			Соединение = Новый HTTPСоединение(URI.Хост, Порт, , , , 90, ?(Защищенное, Новый ЗащищенноеСоединениеOpenSSL, Неопределено));
			Запрос = Новый HTTPЗапрос(Путь);
			Если Заголовки <> Неопределено Тогда
				Для Каждого ПараЗаголовка Из Заголовки Цикл
					Запрос.Заголовки.Вставить(ПараЗаголовка.Ключ, ПараЗаголовка.Значение);
				КонецЦикла;
			КонецЕсли;
			Ответ = Соединение.Получить(Запрос);
			Код = Ответ.КодСостояния;
			Если Код >= 300 И Код < 400 Тогда
				Location = ЗаголовокLocationHTTPНаСервере(Ответ);
				СледующийURL = АбсолютныйURLРедиректаНаСервере(URL, Location);
				Если ПустаяСтрока(СледующийURL) Тогда
					Результат.Ошибка = "HTTP " + Формат(Код, "ЧГ=0") + " без Location при загрузке " + URL;
					Возврат Результат;
				КонецЕсли;
				Возврат HTTPПолучитьДвоичныеДанные(СледующийURL, Заголовки, ГлубинаРедиректа + 1);
			КонецЕсли;
			Если Код <> 200 Тогда
				Результат.Ошибка = "HTTP " + Формат(Код, "ЧГ=0") + " при загрузке " + URL;
				Возврат Результат;
			КонецЕсли;
			Результат.Данные = Ответ.ПолучитьТелоКакДвоичныеДанные();
			HTTPОшибка = "";
			Прервать;
		Исключение
			HTTPОшибка = ОписаниеОшибки();
			Если НомерПопытки < 3 Тогда
				ПаузаМсHTTPНаСервере(400 * НомерПопытки);
			КонецЕсли;
		КонецПопытки;
	КонецЦикла;
	
	Если Не ПустаяСтрока(HTTPОшибка) Тогда
		Результат.Ошибка = ТекстОшибкиHTTPЗагрузкиНаСервере(HTTPОшибка, URL);
	КонецЕсли;
'@

$newt = [regex]::Replace($t, $pattern, $replacement, 1)
if ($newt -eq $t) {
  throw "HTTP block pattern not found"
}

$helper = @'

&НаСервере
Процедура ПаузаМсHTTPНаСервере(Миллисекунды)
	
	Целевое = ТекущаяУниверсальнаяДатаВМиллисекундах() + Макс(0, Миллисекунды);
	Пока ТекущаяУниверсальнаяДатаВМиллисекундах() < Целевое Цикл
	КонецЦикла;
	
КонецПроцедуры

&НаСервере
Функция ТекстОшибкиHTTPЗагрузкиНаСервере(ТекстИсключения, URL)
	
	Текст = СокрЛП(ТекстИсключения);
	Если СтрНайти(НРег(Текст), "no headers") > 0 Или СтрНайти(НРег(Текст), "nothing") > 0 Тогда
		Возврат "Сервер 1С не получил ответ от " + URL
			+ " (сеть, прокси или блокировка HTTPS). Проверка обновлений пропущена — скачайте .epf с GitHub вручную.";
	КонецЕсли;
	Возврат "Загрузка по HTTP: " + Текст;
	
КонецФункции

'@

$newt = $newt.Replace("&НаСервере`r`nФункция ЗаголовокLocationHTTPНаСервере", $helper + "&НаСервере`r`nФункция ЗаголовокLocationHTTPНаСервере")
$newt = $newt.Replace("&НаСервере`nФункция ЗаголовокLocationHTTPНаСервере", $helper + "&НаСервере`nФункция ЗаголовокLocationHTTPНаСервере")

[IO.File]::WriteAllText($mod, $newt, [Text.UTF8Encoding]::new($false))
Write-Host "Patched $mod"
